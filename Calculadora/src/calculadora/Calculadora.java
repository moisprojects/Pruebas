    private void numero(String num) {
        if (pulsar==true) {
            if (lblNumeros.getText().equals("0")) {                
                cadenaNumeros = num;
            } else {
                cadenaNumeros += num;
            }
            lblNumeros.setText(cadenaNumeros);
            activado = true;
        }
    }
    
    private void seleccionarOperacion(String signo, String accion) {
        if (activado==true) {
            cuenta++;
            activado = false;
            pulsar = true;
            punto = true;
            if (cuenta<2) {
                operacion = accion;
                primerNumero = Double.parseDouble(cadenaNumeros);
                lblMuestra.setText(String.format("%.2f",primerNumero)+signo);
            } else {
                calcular();
                primerNumero = resultado;
                lblMuestra.setText(lblMuestra.getText()+signo);
                operacion = accion;
            }
            cadenaNumeros = "";
        }
    }
    

    private void calcular() {
        switch (operacion) {
            case "nula" -> {
                lblNumeros.setText(String.format("%.2f", resultado));
            }
            case "sumar" -> {
                segundoNumero = Double.parseDouble(cadenaNumeros);
                resultado = Operar.suma(primerNumero, segundoNumero);
                lblNumeros.setText(String.format("%.2f", resultado));
                cadenaNumeros = String.valueOf(resultado);
            }
            case "restar" -> {
                segundoNumero = Double.parseDouble(cadenaNumeros);
                resultado = Operar.diferencia(primerNumero, segundoNumero);
                lblNumeros.setText(String.format("%.2f", resultado));
                cadenaNumeros = String.valueOf(resultado);
            }
            case "multiplicar" -> {
                segundoNumero = Double.parseDouble(cadenaNumeros);
                resultado = Operar.producto(primerNumero, segundoNumero);
                lblNumeros.setText(String.format("%.2f", resultado));
                cadenaNumeros = String.valueOf(resultado);
            }
            case "dividir" -> {
                segundoNumero = Double.parseDouble(cadenaNumeros);
                if (segundoNumero==0)
                    lblNumeros.setText("NaN");
                else {
                    resultado = Operar.division(primerNumero, segundoNumero);
                    lblNumeros.setText(String.format("%.2f", resultado));
                    cadenaNumeros = String.valueOf(resultado);
                }
            }
            case "potencia" -> {
                segundoNumero = Double.parseDouble(cadenaNumeros);
                resultado = Operar.potencia(primerNumero, segundoNumero);
                lblNumeros.setText(String.format("%.2f", resultado));
                cadenaNumeros = String.valueOf(resultado);
            }
            case "cuadrado" -> {
                primerNumero = Double.parseDouble(cadenaNumeros);
                lblMuestra.setText("("+String.format("%.2f",primerNumero)+")2");
                resultado = Operar.cuadrado(primerNumero);
                lblNumeros.setText(String.format("%.2f", resultado));
                cadenaNumeros = String.valueOf(resultado);
                pulsar = false;
            }
            case "raizCuadrada" -> {
                primerNumero = Double.parseDouble(cadenaNumeros);
                lblMuestra.setText("√("+String.format("%.2f",primerNumero)+")");
                resultado = Operar.raizCuadrada(primerNumero);
                lblNumeros.setText(String.format("%.2f", resultado));
                cadenaNumeros = String.valueOf(resultado);
                pulsar = false;
            }
            case "raizCubica" -> {
                primerNumero = Double.parseDouble(cadenaNumeros);
                lblMuestra.setText("3√("+String.format("%.2f",primerNumero)+")");
                resultado = Operar.raizCubica(primerNumero);
                lblNumeros.setText(String.format("%.2f", resultado));
                cadenaNumeros = String.valueOf(resultado);
                pulsar = false;
            }
            case "raiz" -> {
                segundoNumero = Double.parseDouble(cadenaNumeros);
                resultado = Operar.raiz(primerNumero, segundoNumero);
                lblNumeros.setText(String.format("%.2f", resultado));
                cadenaNumeros = String.valueOf(resultado);
            }
            case "logaritmo" -> {
                primerNumero = Double.parseDouble(cadenaNumeros);
                lblMuestra.setText("log("+String.format("%.2f",primerNumero)+")");
                resultado = Operar.logaritmo(primerNumero);
                lblNumeros.setText(String.format("%.2f", resultado));
                cadenaNumeros = String.valueOf(resultado);
                pulsar = false;
            }
            case "logLeperiano" -> {
                primerNumero = Double.parseDouble(cadenaNumeros);
                lblMuestra.setText("ln("+String.format("%.2f",primerNumero)+")");
                resultado = Operar.logNeperiano(primerNumero);
                lblNumeros.setText(String.format("%.2f", resultado));
                cadenaNumeros = String.valueOf(resultado);
                pulsar = false;
            }
            case "seno" -> {
                primerNumero = Double.parseDouble(cadenaNumeros);
                lblMuestra.setText("sen("+String.format("%.2f",primerNumero)+")");
                resultado = Operar.seno(primerNumero);
                lblNumeros.setText(String.format("%.2f", resultado));
                cadenaNumeros = String.valueOf(resultado);
                pulsar = false;
            }
            case "coseno" -> {
                primerNumero = Double.parseDouble(cadenaNumeros);
                lblMuestra.setText("cos("+String.format("%.2f",primerNumero)+")");
                resultado = Operar.coseno(primerNumero);
                lblNumeros.setText(String.format("%.2f", resultado));
                cadenaNumeros = String.valueOf(resultado);
                pulsar = false;
            }
            case "tangente" -> {
                primerNumero = Double.parseDouble(cadenaNumeros);
                lblMuestra.setText("tan("+String.format("%.2f",primerNumero)+")");
                resultado = Operar.tangente(primerNumero);
                lblNumeros.setText(String.format("%.2f", resultado));
                cadenaNumeros = String.valueOf(resultado);
                pulsar = false;
            }
            default -> {
                lblNumeros.setText(String.format("%.2f", resultado));
            }
        }
        if (! lblMuestra.getText().equals("") && pulsar==true) {
          lblMuestra.setText(lblMuestra.getText()+" "+String.valueOf(segundoNumero));
          punto = false;
        }
    }
    
