    private void btnComaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnComaActionPerformed
        if (punto==true) {
            if (cadenaNumeros.equals("0"))
                cadenaNumeros = "0.";
            else
                cadenaNumeros += "."; 
            lblNumeros.setText(cadenaNumeros);
            punto = false;
        }
    }//GEN-LAST:event_btnComaActionPerformed

    private void btnSignoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSignoActionPerformed
        if (pulsar==true) {
            if (cadenaNumeros.charAt(0)!='-')
                cadenaNumeros = "-"+cadenaNumeros;
            else
                cadenaNumeros = cadenaNumeros.substring(1,cadenaNumeros.length());
            lblNumeros.setText(cadenaNumeros);
        }
    }//GEN-LAST:event_btnSignoActionPerformed

    private void btnCEActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCEActionPerformed
        if (pulsar==true) {
            int tamanho = cadenaNumeros.length();
            if (tamanho>0) {
                if (tamanho==1)
                    cadenaNumeros = "0";
                else
                    cadenaNumeros = cadenaNumeros.substring(0,cadenaNumeros.length()-1);
                lblNumeros.setText(cadenaNumeros);
            }
            for (int i=0;i<cadenaNumeros.length();i++) {
                if (cadenaNumeros.substring(i,i+1).equals(".")) {
                   punto = true;
                   break;
                }
            }
        }
    }//GEN-LAST:event_btnCEActionPerformed

